export function alStoreImagePaths(num: number): string[] {
  const n = AL_STORE_IMAGE_SLOTS[num] ?? 1;
  return Array.from({ length: n }, (_, i) => `/stores/alabama/al-${num}-${i + 1}.jpg`);
}

function parseCoords(directionsUrl: string): { lat: number; lng: number } {
  const raw = directionsUrl.split("destination=")[1]?.split("&")[0] ?? "";
  const [a, b] = raw.split(",");
  const lat = Number.parseFloat(a ?? "NaN");
  const lng = Number.parseFloat(b ?? "NaN");
  return { lat, lng };
}

function m(idx: number): { directionsUrl: string; mapSearchUrl: string; lat: number; lng: number } {
  const directionsUrl = MAPS[idx]!;
  const { lat, lng } = parseCoords(directionsUrl);
  const q = encodeURIComponent(`${lat},${lng}`);
  return {
    directionsUrl,
    mapSearchUrl: `https://www.google.com/maps/search/?api=1&query=${q}`,
    lat,
    lng,
  };
}

